def collect_one(b, method: str):
    plat = b.platform
    # Every filesystem lookup inside this function (load_reference,
    # experiment_results, experiment_logs via load_experiment_metrics,
    # find_latest_experiment_variant, ...) routes through ``design``, which is
    # the DESIGN_NICKNAME used by ORFS for results/logs paths.  The output
    # CSV's "design" column gets the logical DESIGN_NAME (b.design) below.
    design = b.design_nickname
    ref_res = _ref_results(b)   # flow/results/<plat>/<nickname>/<wm_flow_variant>/

    out: dict = {
        "platform": plat, "design": b.design,
        "method": method, "variant": "",
        "dWNS": "", "dTNS": "", "dRWL": "", "dPower": "",
        "dRuntime": "",      # legacy: full-flow runtime delta (kept for the CSV)
        "wm_runtime_s": "",  # NEW: embed-step wall-clock, in seconds
        "Pc": "", "X_P": "", "x_P": "", "X_C": "", "x_C": "", "p_R": "",
    }

    # Populate the embed-step wall-clock for every method that has an embed
    # step.  This is what the paper's Runtime column now reports.  Note we
    # pass ``b.design`` (full DESIGN name) for log filename matching --
    # wm_log filenames are built from ${DESIGN}, not the nickname -- and
    # ``b.design_nickname`` for the baseline-log "<plat>/<nick>" markers.
    wm_runtime = _wm_runtime_for(method, plat, b.design, b.design_nickname)
    if wm_runtime is not None:
        out["wm_runtime_s"] = wm_runtime

    # ------------------------------------------------------------------ #
    # Baseline methods: experiment harness logs/results path               #
    # ------------------------------------------------------------------ #
    if method in BASELINE_METHODS:
        variant_name = BASELINE_VARIANT_MAP[method]
        out["variant"] = variant_name
        if not _baseline_has_run(plat, design, variant_name):
            out["note"] = f"not yet run; bash baselines/{method.lower().replace('-','_')}/run.sh"
            return out

        ref = load_reference(plat, design, b.wm_flow_variant)
        cur = _load_baseline_metrics(plat, design, variant_name)
        if cur is None:
            out["note"] = "failed to load baseline metrics"
            return out

        out["dWNS"]     = _delta(ref.wns_ns,    cur.wns_ns)
        out["dTNS"]     = _delta(ref.tns_ns,    cur.tns_ns)
        out["dRWL"]     = _delta(ref.rwl_um,    cur.rwl_um)
        out["dPower"]   = _delta(ref.power_w,   cur.power_w)
        out["dRuntime"] = _delta(ref.runtime_s, cur.runtime_s)

        base_rdir = experiment_results(plat, design, variant_name)
        pc_parts = []
        X_P, x_P = _baseline_xX(base_rdir, BASELINE_CSV_PREFIX[method])
        out["X_P"] = X_P; out["x_P"] = x_P
        if X_P > 0:
            pc_parts.append(pc_stage(X_P, x_P, 0.5))
        if pc_parts:
            out["Pc"] = pc_total(*pc_parts)
        return out

    # ------------------------------------------------------------------ #
    # PDMarks methods: experiment harness log directories                 #
    # ------------------------------------------------------------------ #
    pc_parts = []

    if method == "P-only":
        var, cur = _find_pdmarks_run(method, plat, design)
        if cur is None:
            out["note"] = f"not yet run; use experiments/drivers/run_p_only.sh"
            return out
        out["variant"] = var
        ref = load_reference(plat, design, b.wm_flow_variant)
        out["dWNS"]     = _delta(ref.wns_ns,    cur.wns_ns)
        out["dTNS"]     = _delta(ref.tns_ns,    cur.tns_ns)
        out["dRWL"]     = _delta(ref.rwl_um,    cur.rwl_um)
        out["dPower"]   = _delta(ref.power_w,   cur.power_w)
        out["dRuntime"] = _delta(ref.runtime_s, cur.runtime_s)
        wm_res = experiment_results(plat, design, var)
        X_P, x_P = _placement_xX(wm_res)
        out["X_P"] = X_P; out["x_P"] = x_P
        if X_P > 0:
            pc_parts.append(pc_stage(X_P, x_P, 0.5))

    elif method == "C-only":
        var, cur = _find_pdmarks_run(method, plat, design)
        if cur is None:
            out["note"] = "not yet run; use experiments/drivers/run_c_only.sh"
            return out
        out["variant"] = var
        ref = load_reference(plat, design, b.wm_flow_variant)
        out["dWNS"]     = _delta(ref.wns_ns,    cur.wns_ns)
        out["dTNS"]     = _delta(ref.tns_ns,    cur.tns_ns)
        out["dRWL"]     = _delta(ref.rwl_um,    cur.rwl_um)
        out["dPower"]   = _delta(ref.power_w,   cur.power_w)
        out["dRuntime"] = _delta(ref.runtime_s, cur.runtime_s)
        wm_res = experiment_results(plat, design, var)
        X_C, x_C = _cts_xX(wm_res)
        out["X_C"] = X_C; out["x_C"] = x_C
        if X_C > 0:
            pc_parts.append(pc_stage(X_C, x_C, 0.5))

    elif method == "R-only":
        var, cur = _find_pdmarks_run(method, plat, design)
        if cur is None:
            out["note"] = "not yet run; use experiments/drivers/run_r_only.sh"
            return out
        out["variant"] = var
        ref = load_reference(plat, design, b.wm_flow_variant)
        out["dWNS"]     = _delta(ref.wns_ns,    cur.wns_ns)
        out["dTNS"]     = _delta(ref.tns_ns,    cur.tns_ns)
        out["dRWL"]     = _delta(ref.rwl_um,    cur.rwl_um)
        out["dPower"]   = _delta(ref.power_w,   cur.power_w)
        out["dRuntime"] = _delta(ref.runtime_s, cur.runtime_s)
        pR, _ = _routing_p(experiment_results(plat, design, var))
        if pR is not None:
            out["p_R"] = pR
            pc_parts.append(pR)
        else:
            pcR = _routing_pc_from_log(plat, design, var)
            if pcR is not None:
                out["Pc"] = pcR

    elif method == "All-stage":
        # The all-stage flow is split across two experiment variants:
        #   embed_var ("pdmarks-all-stage")        -- placement/CTS embed CSVs
        #   ppa_var   ("pdmarks-all-stage-routed") -- 6_report.json + routing wm
        # Use find_latest_experiment_variant (requires 6_report.json) to discover
        # the completed routed variant automatically.
        embed_var = PDMARKS_VARIANT_PREFIX["All-stage"]  # "pdmarks-all-stage"

        explicit = WM_VARIANT_OVERRIDE.get(method)
        if explicit:
            ppa_var = explicit
        else:
            ppa_var = find_latest_experiment_variant(
                plat, design, PDMARKS_VARIANT_PREFIX[method]
            )
        if ppa_var is None:
            out["note"] = "no all-stage run found; run experiments/drivers/run_all_stage.sh"
            return out

        ref = load_reference(plat, design, b.wm_flow_variant)
        cur = _load_pdmarks_metrics(plat, design, ppa_var)
        if cur is None:
            out["note"] = f"failed to load metrics from {ppa_var!r}"
            return out

        out["variant"] = ppa_var
        out["dWNS"]     = _delta(ref.wns_ns,    cur.wns_ns)
        out["dTNS"]     = _delta(ref.tns_ns,    cur.tns_ns)
        out["dRWL"]     = _delta(ref.rwl_um,    cur.rwl_um)
        out["dPower"]   = _delta(ref.power_w,   cur.power_w)
        out["dRuntime"] = _delta(ref.runtime_s, cur.runtime_s)

        embed_res = experiment_results(plat, design, embed_var)
        ppa_res   = experiment_results(plat, design, ppa_var)

        X_P, x_P = _placement_xX(embed_res, "_all_stage")
        out["X_P"] = X_P; out["x_P"] = x_P
        if X_P > 0:
            pc_parts.append(pc_stage(X_P, x_P, 0.5))
        X_C, x_C = _cts_xX(embed_res, suffix="_all_stage")
        out["X_C"] = X_C; out["x_C"] = x_C
        if X_C > 0:
            pc_parts.append(pc_stage(X_C, x_C, 0.5))
        pR, _ = _routing_p(ppa_res)
        if pR is not None:
            out["p_R"] = pR
            pc_parts.append(pR)
        else:
            pcR = _routing_pc_from_log(plat, design, ppa_var)
            if pcR is not None:
                pc_parts.append(pcR)

    else:
        out["note"] = f"unknown method: {method}"
        return out

    if pc_parts:
        out["Pc"] = pc_total(*pc_parts)
    return out


def main():
    all_methods = (
        BASELINE_ORDER +
        ["P-only", "C-only", "R-only", "All-stage"]
    )
    for b in ACTIVE_BENCHES:
        for method in all_methods:
            rec = collect_one(b, method)
            slug = f"{b.platform}_{b.design}_{method.lower().replace('-','_').replace(' ','_')}"
            (OUT_DIR / f"ppa_{slug}.json").write_text(json.dumps(rec, indent=2))
            var = rec.get("variant", "?")
            note = rec.get("note", "ok")
            print(f"[ppa] {b.platform}/{b.design}  {method:<18}  variant={var!r}  {note}")
    return 0


